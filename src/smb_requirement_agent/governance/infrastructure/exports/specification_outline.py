"""The Business Requirements Document as an ordered outline of blocks.

Word and Markdown render the same blocks, so the two files always carry the same sections,
numbering, identifiers and wording. Only the typesetting differs.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import UTC, datetime

from smb_requirement_agent.governance.application.specification import (
    SPECIFICATION_TITLE,
    RequirementSpecification,
    SpecificationActor,
    SpecificationEvidence,
    SpecificationResolvable,
    SpecificationSignature,
    SpecificationStatement,
    SpecificationVersionKind,
    StatementOrigin,
)


@dataclass(frozen=True)
class Heading:
    level: int
    text: str


@dataclass(frozen=True)
class Paragraph:
    text: str
    note: bool = False


@dataclass(frozen=True)
class Bullets:
    items: tuple[str, ...]


@dataclass(frozen=True)
class Table:
    headers: tuple[str, ...]
    rows: tuple[tuple[str, ...], ...]


type Block = Heading | Paragraph | Bullets | Table

NONE = "—"
NOT_APPROVED_NOTE = (
    "{what} come from the approved backlog; they are listed once the backlog has received "
    "formal final approval."
)
VERSION_KIND_LABELS = {
    SpecificationVersionKind.REQUIREMENT: "Need",
    SpecificationVersionKind.BREAKDOWN: "Backlog",
}
ORIGIN_LABELS = {
    StatementOrigin.CAPTURED: "Captured with the need",
    StatementOrigin.ANALYSIS: "Found by the analysis",
    StatementOrigin.ACCEPTED_PROPOSAL: "Accepted proposal",
}


def outline(document: RequirementSpecification) -> tuple[Block, ...]:
    manifest = document.manifest
    blocks: list[Block] = [
        Heading(0, manifest.title),
        Paragraph(
            f"{SPECIFICATION_TITLE} — Requirement {manifest.requirement_id}, "
            f"revision {manifest.breakdown_revision}."
        ),
        Heading(1, "Document control"),
        Table(
            ("Item", "Value"),
            (
                ("Requirement", manifest.requirement_id),
                ("Requirement version", str(manifest.requirement_version)),
                ("Breakdown revision", str(manifest.breakdown_revision)),
                ("Revision recorded", when(manifest.revision_created_at)),
                ("Analysis round", _optional(manifest.analysis_round)),
                (
                    "Analysis generated",
                    _generated(
                        manifest.analysis_generated_at,
                        manifest.analysis_model,
                        manifest.analysis_prompt_version,
                    ),
                ),
                ("Analysis confirmed", signed(manifest.confirmation)),
                (
                    "Backlog approval",
                    signed(manifest.backlog_approval)
                    if manifest.backlog_approval is not None
                    else "Not yet approved",
                ),
                ("Generated by", manifest.generator),
                ("Document schema", document.schema_version),
            ),
        ),
        Heading(2, "Version history"),
        Table(
            ("Kind", "Version", "Recorded", "Change"),
            tuple(
                (
                    VERSION_KIND_LABELS[item.kind],
                    str(item.number),
                    when(item.recorded_at),
                    item.summary,
                )
                for item in document.versions
            ),
        ),
    ]
    counts = document.summary.counts
    blocks += [
        Heading(1, "1. Executive summary"),
        Paragraph(document.summary.description),
        Paragraph(
            f"The confirmed analysis records {counts.business_requirements} business "
            f"requirements, {counts.business_rules} business rules, {counts.constraints} "
            f"constraints, {counts.assumptions} assumptions, {counts.dependencies} dependencies, "
            f"{counts.open_questions} open questions and {counts.ambiguities} ambiguities; "
            f"{counts.resolved_clarifications} uncertainties were resolved by a person. It "
            f"names {counts.business_use_cases} business use cases and "
            f"{counts.non_functional_requirements} non-functional requirements.",
            note=True,
        ),
        Heading(1, "2. Business objectives"),
    ]
    objectives = document.objectives
    if objectives.desired_outcome is None:
        blocks.append(Paragraph("No desired outcome was recorded.", note=True))
    else:
        blocks.append(Paragraph(objectives.desired_outcome))
        if objectives.origin is not None:
            blocks.append(Paragraph(f"Origin: {ORIGIN_LABELS[objectives.origin]}.", note=True))
    if objectives.success_measures:
        blocks += [Paragraph("Success measures:"), Bullets(objectives.success_measures)]
    scope = document.scope
    blocks.append(Heading(1, "3. Scope"))
    blocks.append(Heading(2, "In scope"))
    blocks.append(
        Paragraph(
            f"Customer context: {scope.customer_context}"
            if scope.customer_context
            else "No customer context was recorded."
        )
    )
    blocks += _named_list("Channels", scope.channels)
    blocks += _named_list("Systems", scope.systems)
    blocks.append(Heading(2, "Out of scope"))
    blocks.append(
        Bullets(scope.out_of_scope)
        if scope.out_of_scope
        else Paragraph("Nothing was recorded as out of scope.", note=True)
    )
    blocks.append(Heading(2, "Current state"))
    blocks.append(
        Paragraph(scope.current_state)
        if scope.current_state
        else Paragraph("The current way of working was not recorded.", note=True)
    )
    blocks.append(Heading(2, "Proposed state"))
    blocks.append(
        Paragraph(scope.proposed_state)
        if scope.proposed_state
        else Paragraph("The proposed way of working was not recorded.", note=True)
    )
    blocks.append(Heading(1, "4. Stakeholders"))
    if document.stakeholders:
        blocks.append(
            Table(
                ("Name", "Role", "Since"),
                tuple(
                    (item.display_name, item.role, when(item.since))
                    for item in document.stakeholders
                ),
            )
        )
    else:
        blocks.append(Paragraph("No owner was recorded for this version.", note=True))
    blocks += _actors(document)
    blocks += _statements("6. Business requirements", document.business_requirements)
    blocks += _use_cases(document)
    blocks += _statements("8. Business rules", document.business_rules)
    blocks += _statements("9. Constraints", document.constraints)
    blocks += _non_functional(document)
    blocks += _resolvables(
        "11. Assumptions",
        document.assumptions,
        "Statement",
        note="Assumptions are not confirmed requirements until a person resolves them.",
    )
    blocks += _resolvables("12. Dependencies", document.dependencies, "Statement")
    blocks += _resolvables(
        "13. Open questions", document.open_questions, "Question", rationale="Why it matters"
    )
    blocks += _resolvables("14. Ambiguities", document.ambiguities, "Statement", rationale="Reason")
    blocks += _product_impact(document)
    blocks += _functional_requirements(document)
    blocks += _risks(document)
    blocks.append(Heading(1, "18. Source documents"))
    if document.source_documents:
        blocks.append(
            Table(
                ("File", "Version", "SHA-256"),
                tuple(
                    (item.filename, item.version_id, item.checksum_sha256)
                    for item in document.source_documents
                ),
            )
        )
    else:
        blocks.append(Paragraph("The analysis cites no source documents.", note=True))
    blocks += [
        Heading(1, "19. Approvals"),
        Table(
            ("Act", "Record"),
            (
                ("Analysis confirmation", signed(manifest.confirmation)),
                (
                    "Backlog final approval",
                    signed(manifest.backlog_approval)
                    if manifest.backlog_approval is not None
                    else "Pending",
                ),
            ),
        ),
        Heading(1, "20. Glossary"),
        Table(
            ("Term", "Definition"),
            tuple((item.term, item.definition) for item in document.glossary),
        ),
    ]
    return tuple(blocks)


def when(value: datetime) -> str:
    return value.astimezone(UTC).strftime("%Y-%m-%d %H:%M UTC")


def signed(signature: SpecificationSignature) -> str:
    text = f"{signature.actor.display_name}, {when(signature.recorded_at)}"
    if signature.rationale:
        text += f" — {signature.rationale}"
    return text


def label(value: str) -> str:
    """A stored enum value as document text: `component_system` reads "Component system"."""
    words = value.replace("_", " ").strip()
    return words.upper() if words.lower() == "mvp" else words[:1].upper() + words[1:]


def _optional(value: int | None) -> str:
    return str(value) if value is not None else NONE


def _generated(at: datetime | None, model: str | None, prompt_version: str | None) -> str:
    if at is None and model is None:
        return NONE
    parts = [when(at)] if at is not None else []
    if model:
        parts.append(f"model {model}")
    if prompt_version:
        parts.append(f"prompt {prompt_version}")
    return ", ".join(parts)


def _named_list(name: str, items: tuple[str, ...]) -> list[Block]:
    if not items:
        return [Paragraph(f"{name}: none recorded.", note=True)]
    return [Paragraph(f"{name}:"), Bullets(items)]


def _evidence(items: tuple[SpecificationEvidence, ...]) -> str:
    if not items:
        return NONE
    return "; ".join(f"{item.filename} ({item.label})" for item in items)


def _statements(title: str, items: tuple[SpecificationStatement, ...]) -> list[Block]:
    if not items:
        return [Heading(1, title), Paragraph("None recorded.", note=True)]
    return [
        Heading(1, title),
        Table(
            ("ID", "Statement", "Origin", "Evidence"),
            tuple(
                (item.id, item.text, ORIGIN_LABELS[item.origin], _evidence(item.evidence))
                for item in items
            ),
        ),
    ]


def _status(item: SpecificationResolvable) -> str:
    resolution = item.resolution
    if resolution is None:
        return "Open"
    who = (
        resolution.answered_by.display_name
        if isinstance(resolution.answered_by, SpecificationActor)
        else None
    )
    stamp = ", ".join(
        part
        for part in (who, when(resolution.answered_at) if resolution.answered_at else None)
        if part
    )
    return f"Resolved: {resolution.answer}" + (f" ({stamp})" if stamp else "")


def _resolvables(
    title: str,
    items: tuple[SpecificationResolvable, ...],
    text_header: str,
    *,
    rationale: str | None = None,
    note: str | None = None,
) -> list[Block]:
    blocks: list[Block] = [Heading(1, title)]
    if note:
        blocks.append(Paragraph(note, note=True))
    if not items:
        blocks.append(Paragraph("None recorded.", note=True))
        return blocks
    headers: tuple[str, ...]
    rows: tuple[tuple[str, ...], ...]
    if rationale is None:
        headers = ("ID", text_header, "Evidence", "Status")
        rows = tuple(
            (item.id, item.text, _evidence(item.evidence), _status(item)) for item in items
        )
    else:
        headers = ("ID", text_header, rationale, "Evidence", "Status")
        rows = tuple(
            (item.id, item.text, item.rationale or NONE, _evidence(item.evidence), _status(item))
            for item in items
        )
    blocks.append(Table(headers, rows))
    return blocks


def _actors(document: RequirementSpecification) -> list[Block]:
    """Who the approved Stories are for, and what each actor sets out to do."""
    blocks: list[Block] = [Heading(1, "5. Actors and scenarios")]
    backlog = document.functional_requirements
    if backlog is None:
        blocks.append(
            Paragraph(NOT_APPROVED_NOTE.format(what="Actors and their scenarios"), note=True)
        )
        return blocks
    rows: list[tuple[str, str, str, str]] = []
    spelling: dict[str, str] = {}
    for feature in backlog.features:
        for story in feature.stories:
            key = " ".join(story.role.split()).casefold()
            actor = spelling.setdefault(key, story.role.strip())
            rows.append((actor, story.id, feature.name, story.action))
    if not rows:
        blocks.append(Paragraph("The approved backlog holds no Stories.", note=True))
        return blocks
    rows.sort(key=lambda row: (row[0].casefold(), row[1]))
    blocks.append(Table(("Actor", "Scenario", "Feature", "Goal"), tuple(rows)))
    return blocks


def _risks(document: RequirementSpecification) -> list[Block]:
    """The backlog review's risks, once the backlog they belong to is approved."""
    blocks: list[Block] = [Heading(1, "17. Risks")]
    backlog = document.functional_requirements
    if backlog is None:
        blocks.append(Paragraph(NOT_APPROVED_NOTE.format(what="Risks"), note=True))
    elif not backlog.risks:
        blocks.append(Paragraph("The backlog review recorded no risks.", note=True))
    else:
        blocks.append(
            Table(
                ("Severity", "Risk"),
                tuple((label(item.severity), item.description) for item in backlog.risks),
            )
        )
    return blocks


def _use_cases(document: RequirementSpecification) -> list[Block]:
    """The business use cases the owner confirmed: who, what starts it, the goal, the steps."""
    blocks: list[Block] = [Heading(1, "7. Business use cases")]
    if not document.business_use_cases:
        blocks.append(Paragraph("None recorded.", note=True))
        return blocks
    for item in document.business_use_cases:
        blocks += [
            Heading(2, f"{item.id} {item.name}"),
            Table(
                ("Item", "Value"),
                (
                    ("Actor", item.actor),
                    ("Trigger", item.trigger or NONE),
                    ("Goal", item.goal),
                    (
                        "Business rules",
                        "; ".join(item.business_rules) if item.business_rules else NONE,
                    ),
                    ("Evidence", _evidence(item.evidence)),
                ),
            ),
            Paragraph("Main steps:"),
            Bullets(tuple(f"{number}. {step}" for number, step in enumerate(item.main_steps, 1))),
        ]
        if item.alternate_paths:
            blocks += [Paragraph("Alternate paths:"), Bullets(item.alternate_paths)]
    return blocks


def _non_functional(document: RequirementSpecification) -> list[Block]:
    blocks: list[Block] = [Heading(1, "10. Non-functional requirements")]
    if not document.non_functional_requirements:
        blocks.append(Paragraph("None recorded.", note=True))
        return blocks
    blocks.append(
        Table(
            ("ID", "Statement", "Type", "Evidence"),
            tuple(
                (item.id, item.text, label(item.kind), _evidence(item.evidence))
                for item in document.non_functional_requirements
            ),
        )
    )
    return blocks


def _product_impact(document: RequirementSpecification) -> list[Block]:
    blocks: list[Block] = [Heading(1, "15. Product impact")]
    impact = document.product_impact
    if impact is None:
        blocks.append(Paragraph("Product impact was not assessed.", note=True))
        return blocks
    rows = [
        ("Assessment", label(impact.status)),
        (
            "Suggested verdict",
            label(impact.suggested_verdict) if impact.suggested_verdict else NONE,
        ),
        ("Decided verdict", label(impact.verdict) if impact.verdict else NONE),
        ("Decision", label(impact.decision) if impact.decision else "Pending"),
        ("Offering", impact.offering_name or NONE),
        ("Reason", impact.reason or NONE),
        ("Decided", signed(impact.decided) if impact.decided is not None else NONE),
    ]
    blocks.append(Table(("Item", "Value"), tuple(rows)))
    if impact.systems:
        blocks.append(
            Table(
                ("System", "Role", "Change"),
                tuple((item.name, item.role, label(item.change_type)) for item in impact.systems),
            )
        )
    if impact.gaps:
        blocks.append(
            Table(("Gap", "Reason"), tuple((item.label, item.reason) for item in impact.gaps))
        )
    return blocks


def _functional_requirements(document: RequirementSpecification) -> list[Block]:
    blocks: list[Block] = [Heading(1, "16. Functional requirements")]
    backlog = document.functional_requirements
    if backlog is None:
        blocks.append(
            Paragraph(
                "The backlog for this revision has not received formal final approval; "
                "functional requirements are not included in this document.",
                note=True,
            )
        )
        return blocks
    blocks += [
        Paragraph(f"Approved backlog: {signed(backlog.approval)}", note=True),
        Heading(2, f"Epic: {backlog.epic.name}"),
        Paragraph(f"Outcome: {backlog.epic.outcome}"),
        Paragraph(f"Business case: {backlog.epic.business_case}"),
    ]
    for feature in backlog.features:
        blocks += [
            Heading(2, f"{feature.id} {feature.name}"),
            Table(
                ("Item", "Value"),
                (
                    ("Outcome", feature.outcome),
                    ("Delivery drop", label(feature.delivery_drop)),
                    ("Work kind", label(feature.kind)),
                ),
            ),
        ]
        blocks += (
            [Paragraph("Acceptance criteria:"), Bullets(feature.acceptance_criteria)]
            if feature.acceptance_criteria
            else [Paragraph("No feature-level acceptance criteria were recorded.", note=True)]
        )
        for story in feature.stories:
            blocks += [
                Heading(
                    3,
                    f"{story.id} As a {story.role}, I want {story.action}, so that {story.value}",
                ),
                Paragraph(f"Work kind: {label(story.kind)}", note=True),
            ]
            if story.criteria:
                blocks.append(
                    Table(
                        ("Given", "When", "Then"),
                        tuple((item.given, item.when, item.then) for item in story.criteria),
                    )
                )
    if backlog.dependencies:
        blocks += [
            Heading(2, "Dependencies from the backlog review"),
            Bullets(backlog.dependencies),
        ]
    return blocks
